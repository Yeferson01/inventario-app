-- =========================================================
-- VALIDAR BATCH / DEVICE / PROFILE
-- =========================================================

create or replace function private.validate_sync_mutation_batch_consistency()
returns trigger
language plpgsql
security definer
set search_path = public, private, extensions
as $$
declare
  v_batch record;
begin
  select
    sb.id,
    sb.business_id,
    sb.app_device_id,
    sb.profile_id,
    sb.branch_id,
    sb.status,
    sb.deleted_at
  into v_batch
  from public.sync_batches sb
  where sb.id = new.sync_batch_id;

  if v_batch.id is null then
    raise exception 'sync_mutations.sync_batch_id must reference an existing sync_batch';
  end if;

  if v_batch.deleted_at is not null then
    raise exception 'Cannot add mutation to deleted sync_batch';
  end if;

  if v_batch.status not in ('pending', 'processing') then
    raise exception 'Cannot add mutation to finalized sync_batch';
  end if;

  if new.business_id <> v_batch.business_id then
    raise exception 'sync_mutations.business_id must match sync_batches.business_id';
  end if;

  if new.app_device_id <> v_batch.app_device_id then
    raise exception 'sync_mutations.app_device_id must match sync_batches.app_device_id';
  end if;

  if new.profile_id <> v_batch.profile_id then
    raise exception 'sync_mutations.profile_id must match sync_batches.profile_id';
  end if;

  if v_batch.branch_id is not null then
    if new.branch_id is null or new.branch_id <> v_batch.branch_id then
      raise exception 'sync_mutations.branch_id must match sync_batches.branch_id when batch is branch-scoped';
    end if;
  end if;

  if new.branch_id is not null then
    if not exists (
      select 1
      from public.branches br
      where br.id = new.branch_id
        and br.business_id = new.business_id
        and br.deleted_at is null
        and br.status = 'active'
    ) then
      raise exception 'sync_mutations.branch_id must belong to the same active business';
    end if;
  end if;

  return new;
end;
$$;

comment on function private.validate_sync_mutation_batch_consistency()
is 'Ensures sync mutations match their parent sync batch and branch scope.';

drop trigger if exists trg_sync_mutations_validate_batch_consistency
on public.sync_mutations;

create trigger trg_sync_mutations_validate_batch_consistency
before insert or update of business_id, sync_batch_id, app_device_id, profile_id, branch_id
on public.sync_mutations
for each row
execute function private.validate_sync_mutation_batch_consistency();

-- =========================================================
-- FILL DEFAULTS
-- =========================================================

create or replace function private.fill_sync_mutation_defaults()
returns trigger
language plpgsql
security definer
set search_path = public, private, extensions
as $$
begin
  new.created_by := coalesce(new.created_by, auth.uid());
  new.updated_by := coalesce(new.updated_by, auth.uid());

  if new.idempotency_key is null then
    new.idempotency_key :=
      new.app_device_id::text || ':' || new.client_mutation_id;
  end if;

  if new.status in ('applied', 'skipped', 'conflict', 'error')
     and new.server_processed_at is null then
    new.server_processed_at := now();
  end if;

  return new;
end;
$$;

comment on function private.fill_sync_mutation_defaults()
is 'Fills audit fields, default idempotency key and processed timestamp for sync_mutations.';

drop trigger if exists trg_sync_mutations_fill_defaults
on public.sync_mutations;

create trigger trg_sync_mutations_fill_defaults
before insert or update of status
on public.sync_mutations
for each row
execute function private.fill_sync_mutation_defaults();

-- =========================================================
-- ACTUALIZAR mutation_count DEL BATCH
-- =========================================================

create or replace function private.increment_sync_batch_mutation_count()
returns trigger
language plpgsql
security definer
set search_path = public, private, extensions
as $$
begin
  if new.deleted_at is null then
    update public.sync_batches sb
    set
      mutation_count = mutation_count + 1,
      updated_at = now()
    where sb.id = new.sync_batch_id;
  end if;

  return new;
end;
$$;

comment on function private.increment_sync_batch_mutation_count()
is 'Increments sync_batches.mutation_count when a mutation is added.';

drop trigger if exists trg_sync_mutations_increment_batch_count
on public.sync_mutations;

create trigger trg_sync_mutations_increment_batch_count
after insert
on public.sync_mutations
for each row
execute function private.increment_sync_batch_mutation_count();

