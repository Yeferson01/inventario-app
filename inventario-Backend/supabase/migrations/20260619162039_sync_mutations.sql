-- Fase 6.3 - Sync mutations
-- Objetivo:
-- Registrar cambios individuales hechos offline por la app.
--
-- sync_batches = lote de sincronización
-- sync_mutations = cada cambio local dentro del lote
--
-- Nota:
-- Esta tabla todavía no procesa/aplica cambios automáticamente.
-- La RPC process_sync_batch() vendrá después.

begin;

-- =========================================================
-- SYNC MUTATIONS
-- =========================================================

create table if not exists public.sync_mutations (
  id uuid primary key default extensions.gen_random_uuid(),

  business_id uuid not null references public.businesses(id) on delete restrict,
  sync_batch_id uuid not null references public.sync_batches(id) on delete cascade,
  app_device_id uuid not null references public.app_devices(id) on delete restrict,
  profile_id uuid not null references public.profiles(id) on delete restrict,
  branch_id uuid references public.branches(id) on delete set null,

  client_mutation_id text not null,
  client_sequence integer not null,

  entity_table text not null,
  entity_id uuid not null,

  operation text not null,

  payload jsonb not null default '{}'::jsonb,
  before_payload jsonb,
  changed_fields text[],

  base_version integer,
  base_updated_at timestamp without time zone,

  status text not null default 'pending',

  server_processed_at timestamp without time zone,
  server_entity_version integer,

  error_code text,
  error_message text,

  idempotency_key text,

  created_at timestamp without time zone default now(),
  updated_at timestamp without time zone default now(),
  deleted_at timestamp without time zone,

  created_by uuid references public.profiles(id) on delete set null,
  updated_by uuid references public.profiles(id) on delete set null,
  deleted_by uuid references public.profiles(id) on delete set null,
  delete_reason text,

  version integer not null default 1,
  sync_status text not null default 'synced',
  metadata jsonb not null default '{}'::jsonb,

  constraint sync_mutations_client_mutation_id_not_blank
    check (length(trim(client_mutation_id)) > 0),

  constraint sync_mutations_client_sequence_non_negative
    check (client_sequence >= 0),

  constraint sync_mutations_entity_table_not_blank
    check (length(trim(entity_table)) > 0),

  constraint sync_mutations_entity_table_allowed
    check (
      entity_table in (
        'categories',
        'products',
        'customers',
        'suppliers',

        'purchases',
        'purchase_items',

        'sales',
        'sale_items',
        'sale_payments',

        'inventory_movements',
        'stock_counts',
        'stock_count_items',
        'inventory_transfers',
        'inventory_transfer_items',

        'cash_sessions',
        'cash_registers'
      )
    ),

  constraint sync_mutations_operation_check
    check (
      operation in (
        'insert',
        'update',
        'upsert',
        'soft_delete',
        'delete'
      )
    ),

  constraint sync_mutations_status_check
    check (
      status in (
        'pending',
        'processing',
        'applied',
        'skipped',
        'conflict',
        'error'
      )
    ),

  constraint sync_mutations_payload_object_check
    check (jsonb_typeof(payload) = 'object'),

  constraint sync_mutations_before_payload_object_check
    check (
      before_payload is null
      or jsonb_typeof(before_payload) = 'object'
    ),

  constraint sync_mutations_base_version_positive
    check (
      base_version is null
      or base_version >= 1
    ),

  constraint sync_mutations_server_entity_version_positive
    check (
      server_entity_version is null
      or server_entity_version >= 1
    ),

  constraint sync_mutations_processed_requires_timestamp
    check (
      status in ('pending', 'processing')
      or server_processed_at is not null
    ),

  constraint sync_mutations_error_requires_message
    check (
      status <> 'error'
      or error_message is not null
    ),

  constraint sync_mutations_conflict_requires_message
    check (
      status <> 'conflict'
      or error_message is not null
    ),

  constraint sync_mutations_version_positive
    check (version >= 1),

  constraint sync_mutations_sync_status_check
    check (sync_status in ('synced', 'pending', 'conflict', 'error'))
);

comment on table public.sync_mutations
is 'Individual offline-first mutations uploaded by app devices as part of sync batches.';

comment on column public.sync_mutations.client_mutation_id
is 'Stable local mutation identifier generated by the app/device.';

comment on column public.sync_mutations.client_sequence
is 'Local sequence number used to preserve mutation order inside a batch.';

comment on column public.sync_mutations.entity_table
is 'Target logical table/entity affected by this mutation.';

comment on column public.sync_mutations.entity_id
is 'UUID of the affected entity. For offline-first inserts, the app should generate this ID locally.';

comment on column public.sync_mutations.operation
is 'Mutation operation: insert, update, upsert, soft_delete or delete.';

comment on column public.sync_mutations.payload
is 'New data or patch sent by the client.';

comment on column public.sync_mutations.before_payload
is 'Optional client-side previous data snapshot for conflict detection.';

comment on column public.sync_mutations.base_version
is 'Entity version known by the client when the mutation was created.';

comment on column public.sync_mutations.base_updated_at
is 'Entity updated_at known by the client when the mutation was created.';

comment on column public.sync_mutations.idempotency_key
is 'Optional idempotency key for safe retries.';

