drop policy if exists sync_mutations_delete_blocked on public.sync_mutations;

-- Usuario ve sus propias mutaciones.
-- Admin/settings/security puede auditar las mutaciones del negocio.
create policy sync_mutations_select_allowed
on public.sync_mutations
for select
to authenticated
using (
  deleted_at is null
  and business_id is not null
  and (
    profile_id = auth.uid()
    or private.has_business_permission(business_id, 'settings.business')
    or private.has_business_permission(business_id, 'security_events.read')
  )
);

-- Usuario puede insertar mutaciones en sus propios batches activos.
create policy sync_mutations_insert_own_allowed
on public.sync_mutations
for insert
to authenticated
with check (
  deleted_at is null
  and profile_id = auth.uid()
  and private.is_business_member(business_id)
  and exists (
    select 1
    from public.sync_batches sb
    where sb.id = sync_mutations.sync_batch_id
      and sb.business_id = sync_mutations.business_id
      and sb.app_device_id = sync_mutations.app_device_id
      and sb.profile_id = auth.uid()
      and sb.status in ('pending', 'processing')
      and sb.deleted_at is null
  )
  and exists (
    select 1
    from public.app_devices ad
    where ad.id = sync_mutations.app_device_id
      and ad.business_id = sync_mutations.business_id
      and ad.profile_id = auth.uid()
      and ad.status = 'active'
      and ad.deleted_at is null
  )
);

-- Usuario puede ajustar una mutación propia solo antes de ser procesada.
create policy sync_mutations_update_own_pending_allowed
on public.sync_mutations
for update
to authenticated
using (
  deleted_at is null
  and profile_id = auth.uid()
  and private.is_business_member(business_id)
  and status in ('pending', 'processing')
)
with check (
  profile_id = auth.uid()
  and private.is_business_member(business_id)
);

-- Admin/settings/security puede actualizar estado para auditoría/soporte.
create policy sync_mutations_admin_update_allowed
on public.sync_mutations
for update
to authenticated
using (
  deleted_at is null
  and (
    private.has_business_permission(business_id, 'settings.business')
    or private.has_business_permission(business_id, 'security_events.read')
  )
)
with check (
  private.has_business_permission(business_id, 'settings.business')
  or private.has_business_permission(business_id, 'security_events.read')
);

-- No hard delete.
create policy sync_mutations_delete_blocked
on public.sync_mutations
for delete
to authenticated
using (false);

commit;