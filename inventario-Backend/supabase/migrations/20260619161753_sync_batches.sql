-- =========================================================
-- RLS
-- =========================================================

alter table public.sync_batches enable row level security;

drop policy if exists sync_batches_select_allowed on public.sync_batches;
drop policy if exists sync_batches_insert_own_allowed on public.sync_batches;
drop policy if exists sync_batches_update_own_allowed on public.sync_batches;
drop policy if exists sync_batches_admin_update_allowed on public.sync_batches;
drop policy if exists sync_batches_delete_blocked on public.sync_batches;

-- Usuarios ven sus propios batches.
-- Admin/settings/security puede ver batches del negocio.
create policy sync_batches_select_allowed
on public.sync_batches
for select
to authenticated
using (
  deleted_at is null
  and business_id is not null
  and (
    profile_id = auth.uid()
    or private.has_business_permission(business_id, 'settings.business')
    or private.has_business_permission(business_id, 'security_events.read')
  )
);

-- El usuario puede crear batches de su propio dispositivo.
create policy sync_batches_insert_own_allowed
on public.sync_batches
for insert
to authenticated
with check (
  deleted_at is null
  and profile_id = auth.uid()
  and private.is_business_member(business_id)
  and (
    branch_id is null
    or private.has_branch_access(business_id, branch_id)
  )
  and exists (
    select 1
    from public.app_devices ad
    where ad.id = sync_batches.app_device_id
      and ad.business_id = sync_batches.business_id
      and ad.profile_id = auth.uid()
      and ad.status = 'active'
      and ad.deleted_at is null
  )
);

-- El usuario puede actualizar su propio batch mientras no esté finalizado.
create policy sync_batches_update_own_allowed
on public.sync_batches
for update
to authenticated
using (
  deleted_at is null
  and profile_id = auth.uid()
  and private.is_business_member(business_id)
  and status in ('pending', 'processing')
)
with check (
  profile_id = auth.uid()
  and private.is_business_member(business_id)
);

-- Admin/settings puede actualizar batches del negocio.
create policy sync_batches_admin_update_allowed
on public.sync_batches
for update
to authenticated
using (
  deleted_at is null
  and (
    private.has_business_permission(business_id, 'settings.business')
    or private.has_business_permission(business_id, 'security_events.read')
  )
)
with check (
  private.has_business_permission(business_id, 'settings.business')
  or private.has_business_permission(business_id, 'security_events.read')
);

-- No hard delete.
create policy sync_batches_delete_blocked
on public.sync_batches
for delete
to authenticated
using (false);

commit;